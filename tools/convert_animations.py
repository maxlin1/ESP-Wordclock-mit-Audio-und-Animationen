#!/usr/bin/env python3
"""
Convert the animation files of Manfred Hofmann's Wortuhr_mp3 project
(data/animations/ani_<NAME>.json) into a compact C++ header that is compiled
into the firmware (include/Extras/AnimationData.gen.h).

Every animation is stored with its own colour palette (max. 256 colours), so a
frame of 10 x 11 pixels needs only 110 bytes.

Usage: python3 tools/convert_animations.py [source_dir] [target_header]
"""
import glob
import json
import os
import re
import sys

ROWS = 10
COLS = 11
MAX_FRAMES = 26  # Manfred's MAXFRAMES (25) + 1


def parse_color(text):
    text = text.strip().lstrip("#")
    if not re.fullmatch(r"[0-9a-fA-F]{6}", text):
        raise ValueError(f"invalid colour '{text}'")
    return int(text, 16)


def load_animation(path):
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    name = os.path.basename(path)[len("ani_"):-len(".json")].upper()
    loops = max(1, min(255, int(data.get("Loops", 1))))
    mode = int(data.get("Laufmode", 0))
    if mode not in (0, 1, 2):
        mode = 0

    frames = []
    for i in range(MAX_FRAMES):
        frame = data.get(f"Frame_{i}")
        if not frame:
            break
        delay = int(frame.get("Delay", 0))
        if delay <= 0:
            break  # like the original firmware: delay 0 ends the animation
        pixels = []
        for row in range(ROWS):
            line = frame.get(f"Zeile_{row}", [])
            for col in range(COLS):
                pixels.append(parse_color(line[col]) if col < len(line) else 0)
        frames.append((min(delay, 65535), pixels))

    if not frames:
        return None

    palette = []
    index = {}
    for _, pixels in frames:
        for color in pixels:
            if color not in index:
                index[color] = len(palette)
                palette.append(color)
    if len(palette) > 256:
        raise ValueError(f"{name}: more than 256 colours")

    return {
        "name": name,
        "loops": loops,
        "mode": mode,
        "palette": palette,
        "frames": [(d, [index[c] for c in p]) for d, p in frames],
    }


def c_ident(name):
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    source = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "data", "animations")
    target = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        root, "include", "Extras", "AnimationData.gen.h")

    animations = []
    for path in sorted(glob.glob(os.path.join(source, "ani_*.json"))):
        try:
            animation = load_animation(path)
        except (ValueError, KeyError, json.JSONDecodeError) as error:
            print(f"convert_animations: skipping {path}: {error}")
            continue
        if animation:
            animations.append(animation)

    out = []
    out.append("// Automatically generated by tools/convert_animations.py -- do not modify")
    out.append("// Source: data/animations/ani_*.json (Wortuhr_mp3 by Manfred Hofmann, GPLv3)")
    out.append("#pragma once")
    out.append("#include <Arduino.h>")
    out.append("")
    out.append("namespace animationData {")
    out.append("")
    out.append("struct Animation {")
    out.append("    const char *name;")
    out.append("    uint8_t loops;")
    out.append("    uint8_t mode; // 0 = forward, 1 = forward/backward, 2 = random")
    out.append("    uint8_t frameCount;")
    out.append("    uint16_t paletteSize;")
    out.append("    const uint8_t *palette; // RGB triples")
    out.append("    const uint16_t *delays; // ms per frame")
    out.append("    const uint8_t *pixels;  // frameCount * 110 palette indices")
    out.append("};")
    out.append("")
    out.append(f"constexpr uint8_t ROWS = {ROWS};")
    out.append(f"constexpr uint8_t COLS = {COLS};")
    out.append("")

    for a in animations:
        ident = c_ident(a["name"])
        pal = ", ".join(f"0x{(c >> 16) & 0xFF:02X}, 0x{(c >> 8) & 0xFF:02X}, 0x{c & 0xFF:02X}"
                        for c in a["palette"])
        delays = ", ".join(str(d) for d, _ in a["frames"])
        out.append(f"static const uint8_t palette_{ident}[] PROGMEM = {{{pal}}};")
        out.append(f"static const uint16_t delays_{ident}[] PROGMEM = {{{delays}}};")
        out.append(f"static const uint8_t pixels_{ident}[] PROGMEM = {{")
        for _, pixels in a["frames"]:
            out.append("    " + ", ".join(str(p) for p in pixels) + ",")
        out.append("};")
        out.append("")

    out.append("static const Animation animations[] = {")
    for a in animations:
        ident = c_ident(a["name"])
        out.append(f'    {{"{a["name"]}", {a["loops"]}, {a["mode"]}, {len(a["frames"])}, '
                   f'{len(a["palette"])}, palette_{ident}, delays_{ident}, pixels_{ident}}},')
    out.append("};")
    out.append("")
    out.append(f"constexpr uint8_t COUNT = {len(animations)};")
    out.append("")
    out.append("} // namespace animationData")
    out.append("")

    content = "\n".join(out)
    os.makedirs(os.path.dirname(target), exist_ok=True)
    old = None
    if os.path.exists(target):
        with open(target, "r", encoding="utf-8") as f:
            old = f.read()
    if old != content:
        with open(target, "w", encoding="utf-8") as f:
            f.write(content)
    print(f"convert_animations: {len(animations)} animations -> {target}")


if __name__ == "__main__":
    main()
